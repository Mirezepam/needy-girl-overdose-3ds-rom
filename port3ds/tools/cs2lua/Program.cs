// cs2lua: translates the decompiled NEEDY GIRL OVERDOSE event scripts (C#) into Lua 5.4 modules
// for the 3DS runtime. Uses the Roslyn semantic model so overloads, named arguments, enum
// constants, string concatenation and async calls are resolved exactly.
//
// usage: cs2lua <decompiled Assembly-CSharp dir> <Managed dll dir> <output lua dir>

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Cs2Lua;

public static class Program
{
    // every game class is translated except third-party libraries and demos
    static readonly string[] ExcludedNamespaces =
        { "Rewired", "SFB", "Qitz", "Kyub", "ngov3.demo", "ES3Types", "NGO.Effect.Sample", "CSVUtil", "Extensions" };

    public static int Main(string[] args)
    {
        if (args.Length < 3)
        {
            Console.Error.WriteLine("usage: cs2lua <src dir> <managed dir> <out dir>");
            return 2;
        }
        string src = args[0], managed = args[1], outDir = args[2];
        var parseOpts = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = Directory.EnumerateFiles(src, "*.cs", SearchOption.AllDirectories)
            .Where(f => !f.Contains(Path.DirectorySeparatorChar + "obj" + Path.DirectorySeparatorChar))
            .Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), parseOpts, path: f))
            .ToList();
        var refs = Directory.EnumerateFiles(managed, "*.dll")
            .Where(f => !Path.GetFileName(f).Equals("Assembly-CSharp.dll", StringComparison.OrdinalIgnoreCase))
            .Select(f => MetadataReference.CreateFromFile(f));
        var comp = CSharpCompilation.Create("Assembly-CSharp", trees, refs,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        Console.WriteLine($"parsed {trees.Count} files; compile errors: " +
                          comp.GetDiagnostics().Count(d => d.Severity == DiagnosticSeverity.Error));

        Directory.CreateDirectory(Path.Combine(outDir, "gen"));
        var selected = new List<(INamedTypeSymbol sym, TypeDeclarationSyntax decl, SemanticModel model)>();
        var seenNames = new HashSet<string>();
        foreach (var tree in trees)
        {
            var model = comp.GetSemanticModel(tree);
            foreach (var cd in tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>().Where(t => t is ClassDeclarationSyntax or StructDeclarationSyntax))
            {
                if (model.GetDeclaredSymbol(cd) is not INamedTypeSymbol sym) continue;
                if (sym.ContainingType != null) continue;
                string ns = sym.ContainingNamespace?.ToDisplayString() ?? "";
                if (ExcludedNamespaces.Any(x => ns == x || ns.StartsWith(x + "."))) continue;
                if (sym.IsGenericType || sym.TypeKind == TypeKind.Interface) continue;
                if (!seenNames.Add(sym.Name)) { Console.WriteLine($"  duplicate class name skipped: {sym.ToDisplayString()}"); continue; }
                selected.Add((sym, cd, model));
            }
        }
        var translated = new HashSet<string>(selected.Select(s => s.sym.Name));
        var report = new StringBuilder("# cs2lua report\n\n| class | TODOs |\n|---|---|\n");
        int totalTodo = 0;
        var index = new StringBuilder("-- AUTO-GENERATED by cs2lua: class name -> module\nreturn {\n");
        foreach (var (sym, decl, model) in selected.OrderBy(s => s.sym.Name))
        {
            var t = new Translator(model, sym, translated);
            string lua = t.TranslateClass(decl);
            File.WriteAllText(Path.Combine(outDir, "gen", sym.Name + ".lua"), lua);
            index.Append($"  [\"{sym.Name}\"] = \"gen.{sym.Name}\",\n");
            totalTodo += t.Todos.Count;
            if (t.Todos.Count > 0)
                report.Append($"| {sym.Name} | {t.Todos.Count}: {string.Join("; ", t.Todos.Take(3)).Replace("|", "/")} |\n");
        }
        index.Append("}\n");
        File.WriteAllText(Path.Combine(outDir, "gen", "_index.lua"), index.ToString());
        File.WriteAllText(Path.Combine(outDir, "enums.lua"), EmitEnums(comp));
        File.WriteAllText(Path.Combine(outDir, "schemas.lua"), EmitSchemas(comp));
        report.Insert(0, $"Translated {selected.Count} classes, {totalTodo} TODOs.\n\n");
        File.WriteAllText(Path.Combine(outDir, "cs2lua_report.md"), report.ToString());
        Console.WriteLine($"translated {selected.Count} classes, {totalTodo} TODOs");
        return 0;
    }

    static bool DerivesFrom(INamedTypeSymbol s, string[] bases)
    {
        for (var b = s.BaseType; b != null; b = b.BaseType)
            if (bases.Contains(b.Name)) return true;
        return false;
    }

    static string TypeKey(INamedTypeSymbol t)
    {
        var parts = new List<string>();
        for (var x = t; x != null; x = x.ContainingType) parts.Insert(0, x.Name);
        return string.Join(".", parts);
    }

    // describes serialized fields so Resources.Load can turn Unity's enum ints back into names
    static string FieldKind(ITypeSymbol ft)
    {
        if (ft is IArrayTypeSymbol at) ft = at.ElementType;
        else if (ft is INamedTypeSymbol nt && nt.IsGenericType && nt.Name is "List" or "IList" or "ReactiveCollection" && nt.TypeArguments.Length == 1)
        {
            var el = nt.TypeArguments[0];
            if (el.TypeKind == TypeKind.Enum) return "LE:" + el.Name;
            if (el is INamedTypeSymbol ent && ent.Locations.Any(l => l.IsInSource)) return "LC:" + TypeKey(ent);
            return null;
        }
        if (ft.TypeKind == TypeKind.Enum) return "E:" + ft.Name;
        // scene references (GameObject, Button, Transform, MonoBehaviour components...)
        for (var b = ft as INamedTypeSymbol; b != null; b = b.BaseType)
            if (b.Name == "Object" && b.ContainingNamespace?.ToDisplayString() == "UnityEngine")
                return "U:" + ft.Name;
        if (ft is INamedTypeSymbol ct && (ct.TypeKind == TypeKind.Class || ct.TypeKind == TypeKind.Struct) && ct.Locations.Any(l => l.IsInSource) && !ct.IsGenericType)
            return "C:" + TypeKey(ct);
        return null;
    }

    static string EmitSchemas(Compilation comp)
    {
        var sb = new StringBuilder("-- AUTO-GENERATED by cs2lua: serialized field kinds per type\nreturn {\n");
        var seen = new HashSet<string>();
        foreach (var tree in comp.SyntaxTrees)
        {
            var model = comp.GetSemanticModel(tree);
            foreach (var td in tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>())
            {
                if (model.GetDeclaredSymbol(td) is not INamedTypeSymbol t) continue;
                string key = TypeKey(t);
                if (!seen.Add(key)) continue;
                var fields = t.GetMembers().OfType<IFieldSymbol>().Where(f => !f.IsStatic && !f.IsConst)
                    .Select(f => (f.Name, kind: FieldKind(f.Type))).Where(x => x.kind != null).ToList();
                if (fields.Count == 0) continue;
                sb.Append($"[\"{key}\"]={{");
                foreach (var (n, k) in fields) sb.Append($"[\"{n}\"]=\"{k}\",");
                sb.Append("},\n");
            }
        }
        sb.Append("}\n");
        return sb.ToString();
    }

    static string EmitEnums(Compilation comp)
    {
        var sb = new StringBuilder("-- AUTO-GENERATED by cs2lua: enum name -> {Member = value}\nlocal E = {}\n");
        var seen = new HashSet<string>();
        foreach (var tree in comp.SyntaxTrees)
        {
            var model = comp.GetSemanticModel(tree);
            foreach (var ed in tree.GetRoot().DescendantNodes().OfType<EnumDeclarationSyntax>())
            {
                var sym = model.GetDeclaredSymbol(ed);
                if (sym == null || !seen.Add(sym.Name)) continue;
                sb.Append($"E[\"{sym.Name}\"] = {{");
                foreach (var m in sym.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
                    sb.Append($" [\"{m.Name}\"] = {Convert.ToInt64(m.ConstantValue)},");
                sb.Append(" }\n");
            }
        }
        sb.Append("return E\n");
        return sb.ToString();
    }
}

class Translator
{
    readonly SemanticModel model;
    readonly INamedTypeSymbol self;
    readonly HashSet<string> translated;
    readonly StringBuilder sb = new();
    int indent;
    int tmp;
    readonly Stack<string> condReceivers = new();
    public readonly List<string> Todos = new();

    static readonly HashSet<string> LuaKeywords = new()
    {
        "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in",
        "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while", "self"
    };

    public Translator(SemanticModel model, INamedTypeSymbol self, HashSet<string> translated)
    {
        this.model = model;
        this.self = self;
        this.translated = translated;
    }

    // ---------------------------------------------------------------- output helpers
    // a Lua statement starting with "(" would continue the previous call: separate it with ";"
    void Line(string s) => sb.Append(new string(' ', indent * 2)).Append(s.StartsWith('(') ? ";" + s : s).Append('\n');

    string Todo(SyntaxNode n)
    {
        string code = n.ToString().Split('\n')[0].Trim();
        if (code.Length > 100) code = code[..100];
        Todos.Add($"{n.Kind()}: {code}");
        return Lit(code);
    }

    static string Lit(string s)
    {
        var b = new StringBuilder("\"");
        foreach (char c in s)
        {
            switch (c)
            {
                case '\\': b.Append("\\\\"); break;
                case '"': b.Append("\\\""); break;
                case '\n': b.Append("\\n"); break;
                case '\r': b.Append("\\r"); break;
                case '\t': b.Append("\\t"); break;
                case '\0': b.Append("\\0"); break;
                default: b.Append(c); break;
            }
        }
        return b.Append('"').ToString();
    }

    static string Name(string n)
    {
        if (n.StartsWith('@')) n = n[1..];
        return LuaKeywords.Contains(n) ? n + "_" : n;
    }

    // ---------------------------------------------------------------- classes
    public string TranslateClass(TypeDeclarationSyntax cd)
    {
        string baseName = self.TypeKind == TypeKind.Struct ? "Object" : self.BaseType?.Name ?? "Object";
        Line($"-- AUTO-GENERATED by cs2lua from {Path.GetFileName(cd.SyntaxTree.FilePath)}. Do not edit.");
        Line($"local C = class({Lit(self.Name)}, {Lit(baseName)})");
        Line("");

        // static fields
        foreach (var fd in cd.Members.OfType<FieldDeclarationSyntax>().Where(f => f.Modifiers.Any(SyntaxKind.StaticKeyword)))
            foreach (var v in fd.Declaration.Variables)
                Line($"C.{Name(v.Identifier.Text)} = {(v.Initializer != null ? Expr(v.Initializer.Value) : DefaultFor(model.GetTypeInfo(fd.Declaration.Type).Type))}");

        // instance field initializers (with a primary constructor they run in __ctor_1 instead)
        bool primary = cd.ParameterList != null;
        Line("function C:__fields()");
        indent++;
        Line("if C.super and C.super.__fields then C.super.__fields(self) end");
        foreach (var fd in cd.Members.OfType<FieldDeclarationSyntax>().Where(f => !f.Modifiers.Any(SyntaxKind.StaticKeyword) && !f.Modifiers.Any(SyntaxKind.ConstKeyword)))
            foreach (var v in fd.Declaration.Variables)
                Line($"self.{Name(v.Identifier.Text)} = {(v.Initializer != null && !primary ? Expr(v.Initializer.Value) : DefaultFor(model.GetTypeInfo(fd.Declaration.Type).Type))}");
        foreach (var pd in cd.Members.OfType<PropertyDeclarationSyntax>())
        {
            bool auto = pd.AccessorList != null && pd.AccessorList.Accessors.All(a => a.Body == null && a.ExpressionBody == null);
            if (auto && !pd.Modifiers.Any(SyntaxKind.StaticKeyword))
                Line($"self.{Name(pd.Identifier.Text)} = {(pd.Initializer != null ? Expr(pd.Initializer.Value) : DefaultFor(model.GetTypeInfo(pd.Type).Type))}");
        }
        indent--;
        Line("end");
        Line("");

        // computed properties -> getters / setters
        foreach (var pd in cd.Members.OfType<PropertyDeclarationSyntax>())
        {
            var setAcc = pd.AccessorList?.Accessors.FirstOrDefault(a => a.IsKind(SyntaxKind.SetAccessorDeclaration));
            if (setAcc != null && (setAcc.Body != null || setAcc.ExpressionBody != null))
            {
                Line($"C.__setters[{Lit(pd.Identifier.Text)}] = function(self, value)");
                indent++;
                if (setAcc.ExpressionBody != null) ExprStatement(setAcc.ExpressionBody.Expression);
                else Block(setAcc.Body.Statements);
                indent--;
                Line("end");
            }
            var getter = pd.ExpressionBody?.Expression;
            var getAcc = pd.AccessorList?.Accessors.FirstOrDefault(a => a.IsKind(SyntaxKind.GetAccessorDeclaration));
            if (getter == null && getAcc?.Body == null && getAcc?.ExpressionBody == null) continue;
            Line($"C.__getters[{Lit(pd.Identifier.Text)}] = function(self)");
            indent++;
            if (getter != null) Line("return " + Expr(getter));
            else if (getAcc.ExpressionBody != null) Line("return " + Expr(getAcc.ExpressionBody.Expression));
            else Block(getAcc.Body.Statements);
            indent--;
            Line("end");
        }

        if (primary)
        {
            Line($"function C:__ctor_1({Params(cd.ParameterList)})");
            indent++;
            foreach (var fd in cd.Members.OfType<FieldDeclarationSyntax>().Where(f => !f.Modifiers.Any(SyntaxKind.StaticKeyword) && !f.Modifiers.Any(SyntaxKind.ConstKeyword)))
                foreach (var v in fd.Declaration.Variables.Where(v => v.Initializer != null))
                    Line($"self.{Name(v.Identifier.Text)} = {Expr(v.Initializer.Value)}");
            indent--;
            Line("end");
            Line("");
        }

        // constructors (overloads numbered in declaration order)
        var ctors = cd.Members.OfType<ConstructorDeclarationSyntax>().Where(c => !c.Modifiers.Any(SyntaxKind.StaticKeyword)).ToList();
        for (int i = 0; i < ctors.Count; i++)
        {
            var c = ctors[i];
            Line($"function C:__ctor_{i + 1}({Params(c.ParameterList)})");
            indent++;
            if (c.Initializer != null)
            {
                var target = model.GetSymbolInfo(c.Initializer).Symbol as IMethodSymbol;
                string args = Args(c.Initializer.ArgumentList, target);
                string who = c.Initializer.IsKind(SyntaxKind.BaseConstructorInitializer) ? "C.super" : "C";
                Line($"{who}.__ctor_{CtorIndex(target)}(self{(args.Length > 0 ? ", " + args : "")})");
            }
            if (c.Body != null) Block(c.Body.Statements);
            else if (c.ExpressionBody != null) Line(Expr(c.ExpressionBody.Expression));
            indent--;
            Line("end");
            Line("");
        }

        foreach (var md in cd.Members.OfType<MethodDeclarationSyntax>())
        {
            var ms = model.GetDeclaredSymbol(md);
            string sep = ms.IsStatic ? "." : ":";
            // generic type parameters become leading arguments holding the type name
            string tps = md.TypeParameterList != null ? string.Join(", ", md.TypeParameterList.Parameters.Select(tp => Name(tp.Identifier.Text))) : "";
            string ps = Params(md.ParameterList);
            string allParams = tps.Length > 0 && ps.Length > 0 ? tps + ", " + ps : tps + ps;
            Line($"function C{sep}{MethodName(ms)}({allParams})");
            indent++;
            // async methods called from outside a coroutine (UI, callbacks) start their own task,
            // like C#: they run until the first await and the caller continues
            if (ms.IsAsync)
            {
                string selfArg = ms.IsStatic ? "" : "self";
                string spawnArgs = string.Join(", ", new[] { selfArg, allParams }.Where(x => x.Length > 0));
                Line($"if not coroutine.isyieldable() then spawn(C.{MethodName(ms)}{(spawnArgs.Length > 0 ? ", " + spawnArgs : "")}) return end");
            }
            if (md.Body != null) Block(md.Body.Statements);
            else if (md.ExpressionBody != null) ExprBodyStatement(md.ExpressionBody.Expression, !ms.ReturnsVoid && !IsTaskType(ms.ReturnType));
            indent--;
            Line("end");
            Line("");
        }
        Line("return C");
        return sb.ToString();
    }

    int CtorIndex(IMethodSymbol ctor)
    {
        if (ctor == null) return 1;
        var t = ctor.ContainingType;
        var all = t.InstanceConstructors.Where(c => !c.IsImplicitlyDeclared)
            .OrderBy(c => c.Locations.FirstOrDefault()?.SourceSpan.Start ?? 0).ToList();
        int i = all.FindIndex(c => SymbolEqualityComparer.Default.Equals(c, ctor));
        return i < 0 ? 1 : i + 1;
    }

    string MethodName(IMethodSymbol m)
    {
        var def = m.OriginalDefinition;
        if (m.MethodKind == MethodKind.ReducedExtension) def = m.ReducedFrom.OriginalDefinition;
        // overloads of translated source types get a numeric suffix; runtime types keep the plain name
        if (translated.Contains(def.ContainingType.Name) && def.MethodKind == MethodKind.Ordinary)
        {
            var group = def.ContainingType.GetMembers(def.Name).OfType<IMethodSymbol>().Where(x => !x.IsImplicitlyDeclared)
                .OrderBy(x => x.Locations.FirstOrDefault()?.SourceSpan.Start ?? 0).ToList();
            if (group.Count > 1 && !def.IsOverride && !def.IsVirtual)
                return Name(def.Name) + "_" + (group.FindIndex(x => SymbolEqualityComparer.Default.Equals(x, def)) + 1);
        }
        return Name(def.Name);
    }

    string Params(BaseParameterListSyntax pl) =>
        string.Join(", ", pl.Parameters.Select(p => Name(p.Identifier.Text)));

    static bool IsTaskType(ITypeSymbol t) =>
        t != null && (t.Name is "UniTask" or "Task" or "UniTaskVoid" or "IEnumerator");

    string DefaultFor(ITypeSymbol t)
    {
        if (t == null) return "nil";
        if (t.TypeKind == TypeKind.Enum)
        {
            var zero = t.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(f => f.HasConstantValue && Convert.ToInt64(f.ConstantValue) == 0);
            return zero != null ? Lit(zero.Name) : "nil";
        }
        return t.SpecialType switch
        {
            SpecialType.System_Boolean => "false",
            SpecialType.System_Int16 or SpecialType.System_Int32 or SpecialType.System_Int64 or SpecialType.System_Byte or
            SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_Decimal or SpecialType.System_UInt32 => "0",
            _ => t.IsValueType && t.SpecialType == SpecialType.None ? $"NEW({Lit(t.Name)})" : "nil",
        };
    }

    // ---------------------------------------------------------------- statements
    void Block(SyntaxList<StatementSyntax> stmts)
    {
        for (int i = 0; i < stmts.Count; i++)
            Stmt(stmts[i], i == stmts.Count - 1);
    }

    void Body(StatementSyntax s)
    {
        if (s is BlockSyntax b) Block(b.Statements);
        else Stmt(s, true);
    }

    void ExprBodyStatement(ExpressionSyntax e, bool returns)
    {
        if (returns) Line("return " + Expr(e));
        else ExprStatement(e);
    }

    void Stmt(StatementSyntax s, bool last)
    {
        if (s is ExpressionStatementSyntax or LocalDeclarationStatementSyntax or IfStatementSyntax or ReturnStatementSyntax or WhileStatementSyntax)
            DeclareOutVars(s);
        switch (s)
        {
            case BlockSyntax b:
                Line("do"); indent++; Block(b.Statements); indent--; Line("end");
                break;
            case LocalDeclarationStatementSyntax ld:
                foreach (var v in ld.Declaration.Variables)
                    Line($"local {Name(v.Identifier.Text)} = {(v.Initializer != null ? Expr(v.Initializer.Value) : "nil")}");
                break;
            case ExpressionStatementSyntax es:
                ExprStatement(es.Expression);
                break;
            case ReturnStatementSyntax rs:
                string r = rs.Expression != null ? "return " + Expr(rs.Expression) : "return";
                Line(last ? r : $"do {r} end");
                break;
            case IfStatementSyntax ifs:
                If(ifs, "if");
                Line("end");
                break;
            case SwitchStatementSyntax sw:
                Switch(sw);
                break;
            case WhileStatementSyntax ws:
                Line($"while {Expr(ws.Condition)} do");
                LoopBody(ws.Statement, null);
                Line("end");
                break;
            case DoStatementSyntax ds:
                Line("repeat");
                LoopBody(ds.Statement, null);
                Line($"until not ({Expr(ds.Condition)})");
                break;
            case ForStatementSyntax fs:
                Line("do");
                indent++;
                if (fs.Declaration != null)
                    foreach (var v in fs.Declaration.Variables)
                        Line($"local {Name(v.Identifier.Text)} = {(v.Initializer != null ? Expr(v.Initializer.Value) : "nil")}");
                foreach (var init in fs.Initializers) ExprStatement(init);
                Line($"while {(fs.Condition != null ? Expr(fs.Condition) : "true")} do");
                LoopBody(fs.Statement, fs.Incrementors);
                Line("end");
                indent--;
                Line("end");
                break;
            case ForEachStatementSyntax fe:
                Line($"for _, {Name(fe.Identifier.Text)} in EACH({Expr(fe.Expression)}) do");
                LoopBody(fe.Statement, null);
                Line("end");
                break;
            case BreakStatementSyntax:
                Line("break");
                break;
            case ContinueStatementSyntax:
                Line("goto continue");
                break;
            case ThrowStatementSyntax th:
                Line(th.Expression != null ? $"error({Expr(th.Expression)})" : "error(__err)");
                break;
            case TryStatementSyntax ts:
                Try(ts);
                break;
            case UsingStatementSyntax us:
                if (us.Declaration != null)
                    foreach (var v in us.Declaration.Variables)
                        Line($"local {Name(v.Identifier.Text)} = {Expr(v.Initializer.Value)}");
                Line("do"); indent++; Body(us.Statement); indent--; Line("end");
                break;
            case LockStatementSyntax ls:
                Line("do"); indent++; Body(ls.Statement); indent--; Line("end");
                break;
            case LocalFunctionStatementSyntax lf:
                Line($"local function {Name(lf.Identifier.Text)}({Params(lf.ParameterList)})");
                indent++;
                if (lf.Body != null) Block(lf.Body.Statements);
                else ExprBodyStatement(lf.ExpressionBody.Expression, true);
                indent--;
                Line("end");
                break;
            case EmptyStatementSyntax:
                break;
            default:
                Line($"TODO({Todo(s)})");
                break;
        }
    }

    void LoopBody(StatementSyntax body, SeparatedSyntaxList<ExpressionSyntax>? incrementors)
    {
        bool hasContinue = body.DescendantNodesAndSelf(n => n == body || !(n is ForStatementSyntax or WhileStatementSyntax or DoStatementSyntax or ForEachStatementSyntax))
            .OfType<ContinueStatementSyntax>().Any();
        indent++;
        if (hasContinue) { Line("do"); indent++; }
        Body(body);
        if (hasContinue) { indent--; Line("end"); Line("::continue::"); }
        if (incrementors != null)
            foreach (var inc in incrementors) ExprStatement(inc);
        indent--;
    }

    void If(IfStatementSyntax ifs, string kw)
    {
        Line($"{kw} {Expr(ifs.Condition)} then");
        indent++; Body(ifs.Statement); indent--;
        if (ifs.Else == null) return;
        if (ifs.Else.Statement is IfStatementSyntax elif) If(elif, "elseif");
        else
        {
            Line("else");
            indent++; Body(ifs.Else.Statement); indent--;
        }
    }

    void Switch(SwitchStatementSyntax sw)
    {
        string v = "__sw" + (++tmp);
        // repeat ... until true lets C# `break` leave the switch
        Line("repeat");
        indent++;
        Line($"local {v} = {Expr(sw.Expression)}");
        bool first = true;
        SwitchSectionSyntax def = null;
        foreach (var sec in sw.Sections)
        {
            var conds = new List<string>();
            foreach (var label in sec.Labels)
            {
                switch (label)
                {
                    case DefaultSwitchLabelSyntax: break;
                    case CaseSwitchLabelSyntax c: conds.Add($"{v} == {Expr(c.Value)}"); break;
                    case CasePatternSwitchLabelSyntax p: conds.Add(Pattern(v, p.Pattern) + (p.WhenClause != null ? $" and ({Expr(p.WhenClause.Condition)})" : "")); break;
                }
            }
            if (sec.Labels.Any(l => l is DefaultSwitchLabelSyntax) && conds.Count == 0) { def = sec; continue; }
            Line($"{(first ? "if" : "elseif")} {string.Join(" or ", conds)} then");
            first = false;
            indent++; SectionBody(sec); indent--;
        }
        if (def != null)
        {
            if (first) { SectionBody(def); }
            else { Line("else"); indent++; SectionBody(def); indent--; }
        }
        if (!first) Line("end");
        indent--;
        Line("until true");
    }

    void SectionBody(SwitchSectionSyntax sec)
    {
        var stmts = sec.Statements.ToList();
        if (stmts.Count == 1 && stmts[0] is BlockSyntax blk) stmts = blk.Statements.ToList();
        if (stmts.Count > 0 && stmts[^1] is BreakStatementSyntax) stmts.RemoveAt(stmts.Count - 1);
        for (int i = 0; i < stmts.Count; i++) Stmt(stmts[i], i == stmts.Count - 1);
    }

    string Pattern(string v, PatternSyntax p) => p switch
    {
        ConstantPatternSyntax c => c.Expression.IsKind(SyntaxKind.NullLiteralExpression) ? $"{v} == nil" : $"{v} == {Expr(c.Expression)}",
        DiscardPatternSyntax => "true",
        RelationalPatternSyntax r => $"{v} {r.OperatorToken.Text} {Expr(r.Expression)}",
        BinaryPatternSyntax b => $"({Pattern(v, b.Left)} {(b.OperatorToken.IsKind(SyntaxKind.OrKeyword) ? "or" : "and")} {Pattern(v, b.Right)})",
        UnaryPatternSyntax u => $"not ({Pattern(v, u.Pattern)})",
        TypePatternSyntax t => $"IS({v}, {Lit(t.Type.ToString())})",
        DeclarationPatternSyntax d => $"IS({v}, {Lit(d.Type.ToString())})",
        _ => $"TODO_EXPR({Todo(p)})",
    };

    void Try(TryStatementSyntax ts)
    {
        if (ts.Block.DescendantNodes().OfType<ReturnStatementSyntax>().Any())
            Todos.Add("return inside try: semantics approximated");
        string ok = "__ok" + (++tmp);
        Line($"local {ok}, __err = pcall(function()");
        indent++; Block(ts.Block.Statements); indent--;
        Line("end)");
        if (ts.Catches.Count > 0)
        {
            Line($"if not {ok} then");
            indent++;
            var c = ts.Catches[0];
            string ctype = c.Declaration?.Type.ToString() ?? "";
            // catch (OperationCanceledException) must not swallow real errors
            if (ctype.EndsWith("OperationCanceledException")) Line("if not IS_CANCEL(__err) then error(__err, 0) end");
            else Line("LOG_ERROR(__err)");
            if (c.Declaration != null && c.Declaration.Identifier.Text.Length > 0)
                Line($"local {Name(c.Declaration.Identifier.Text)} = __err");
            Block(c.Block.Statements);
            indent--;
            Line("end");
        }
        if (ts.Finally != null) Block(ts.Finally.Block.Statements);
        if (ts.Catches.Count == 0) Line($"if not {ok} then error(__err) end");
    }

    void ExprStatement(ExpressionSyntax e)
    {
        switch (e)
        {
            case AssignmentExpressionSyntax a:
                Line(Assign(a));
                return;
            case PostfixUnaryExpressionSyntax pu when pu.IsKind(SyntaxKind.PostIncrementExpression) || pu.IsKind(SyntaxKind.PostDecrementExpression):
                Line(IncDec(pu.Operand, pu.IsKind(SyntaxKind.PostIncrementExpression) ? "+" : "-"));
                return;
            case PrefixUnaryExpressionSyntax pr when pr.IsKind(SyntaxKind.PreIncrementExpression) || pr.IsKind(SyntaxKind.PreDecrementExpression):
                Line(IncDec(pr.Operand, pr.IsKind(SyntaxKind.PreIncrementExpression) ? "+" : "-"));
                return;
            case AwaitExpressionSyntax aw:
                string awaited = Expr(aw.Expression);
                bool awaitedCall = aw.Expression is InvocationExpressionSyntax or ConditionalAccessExpressionSyntax;
                Line(awaitedCall ? awaited : "local _ = " + awaited);
                return;
        }
        string code = Expr(e);
        bool callLike = e is InvocationExpressionSyntax or ConditionalAccessExpressionSyntax or ObjectCreationExpressionSyntax;
        if (!callLike) code = "local _ = " + code;
        // un-awaited async call: C# runs it until its first await, then continues -> spawn()
        if (IsAsyncCall(e)) code = $"spawn(function() {code} end)";
        Line(code);
    }

    bool IsAsyncCall(ExpressionSyntax e)
    {
        if (e is not InvocationExpressionSyntax and not ConditionalAccessExpressionSyntax) return false;
        var inv = e as InvocationExpressionSyntax ?? (e as ConditionalAccessExpressionSyntax)?.WhenNotNull as InvocationExpressionSyntax;
        if (inv == null) return false;
        if (model.GetSymbolInfo(inv).Symbol is not IMethodSymbol m) return false;
        return m.IsAsync || IsTaskType(m.ReturnType);
    }

    string IncDec(ExpressionSyntax target, string op)
    {
        if (target is ElementAccessExpressionSyntax ea)
        {
            string o = Expr(ea.Expression), i = Expr(ea.ArgumentList.Arguments[0].Expression);
            return $"SETIDX({o}, {i}, IDX({o}, {i}) {op} 1)";
        }
        string t = Expr(target);
        return $"{t} = {t} {op} 1";
    }

    string Assign(AssignmentExpressionSyntax a)
    {
        string op = a.OperatorToken.Text;
        string rhs = Expr(a.Right);
        if (op != "=")
        {
            string bop = op[..^1];
            if (bop == "??") rhs = $"nz({Expr(a.Left)}, {rhs})";
            else if (bop == "+" && IsString(a.Left)) rhs = $"CONCAT({Expr(a.Left)}, {rhs})";
            else if (bop == "+" && model.GetSymbolInfo(a.Left).Symbol is IEventSymbol) return $"TODO({Todo(a)})";
            else if (bop == "/" && IsIntegral(a.Left) && IsIntegral(a.Right)) rhs = $"IDIV({Expr(a.Left)}, {rhs})";
            else if (bop is "&" or "|" or "^") rhs = $"BIT{(bop == "&" ? "AND" : bop == "|" ? "OR" : "XOR")}({Expr(a.Left)}, {rhs})";
            else rhs = $"{Expr(a.Left)} {bop} {rhs}";
        }
        if (a.Left is ElementAccessExpressionSyntax ea)
            return $"SETIDX({Expr(ea.Expression)}, {Expr(ea.ArgumentList.Arguments[0].Expression)}, {rhs})";
        if (a.Left is IdentifierNameSyntax { Identifier.Text: "_" }) return $"local _ = {rhs}";
        if (a.Left is TupleExpressionSyntax) return $"TODO({Todo(a)})";
        return $"{Expr(a.Left)} = {rhs}";
    }

    // ---------------------------------------------------------------- expressions
    bool IsString(ExpressionSyntax e) => model.GetTypeInfo(e).Type?.SpecialType == SpecialType.System_String;

    bool IsIntegral(ExpressionSyntax e) => model.GetTypeInfo(e).Type?.SpecialType is
        SpecialType.System_Int32 or SpecialType.System_Int64 or SpecialType.System_Int16 or SpecialType.System_Byte or SpecialType.System_UInt32;

    bool IsEnum(ExpressionSyntax e) => model.GetTypeInfo(e).Type?.TypeKind == TypeKind.Enum;

    string Expr(ExpressionSyntax e)
    {
        var cv = model.GetConstantValue(e);
        if (cv.HasValue && e is not LiteralExpressionSyntax && !IsEnum(e))
            return ConstLit(cv.Value);

        switch (e)
        {
            case LiteralExpressionSyntax lit:
                return lit.Kind() switch
                {
                    SyntaxKind.NullLiteralExpression => "nil",
                    SyntaxKind.TrueLiteralExpression => "true",
                    SyntaxKind.FalseLiteralExpression => "false",
                    SyntaxKind.DefaultLiteralExpression => DefaultFor(model.GetTypeInfo(e).ConvertedType),
                    _ => ConstLit(lit.Token.Value),
                };
            case ParenthesizedExpressionSyntax p:
                return "(" + Expr(p.Expression) + ")";
            case IdentifierNameSyntax id:
                return Identifier(id);
            case GenericNameSyntax gn:
                return Identifier(gn);
            case ThisExpressionSyntax:
                return "self";
            case BaseExpressionSyntax:
                return "C.super";
            case MemberAccessExpressionSyntax ma:
                return MemberAccess(ma);
            case MemberBindingExpressionSyntax mb:
                return condReceivers.Peek() + "." + Name(mb.Name.Identifier.Text);
            case InvocationExpressionSyntax inv:
            {
                string call = Invocation(inv);
                var outs = inv.ArgumentList.Arguments.Where(a => a.RefKindKeyword.IsKind(SyntaxKind.OutKeyword)).Select(OutTarget).ToList();
                if (outs.Count == 0) return call;
                return $"(function() local __r; __r, {string.Join(", ", outs)} = {call}; return __r end)()";
            }
            case AwaitExpressionSyntax aw:
                return Expr(aw.Expression);
            case BinaryExpressionSyntax be:
                return Binary(be);
            case PrefixUnaryExpressionSyntax pu:
                return pu.Kind() switch
                {
                    SyntaxKind.LogicalNotExpression => $"not {Expr(pu.Operand)}",
                    SyntaxKind.UnaryMinusExpression => $"-{Expr(pu.Operand)}",
                    SyntaxKind.UnaryPlusExpression => Expr(pu.Operand),
                    SyntaxKind.BitwiseNotExpression => $"BITNOT({Expr(pu.Operand)})",
                    _ => $"TODO_EXPR({Todo(e)})",
                };
            case PostfixUnaryExpressionSyntax pf when pf.IsKind(SyntaxKind.SuppressNullableWarningExpression):
                return Expr(pf.Operand);
            case ConditionalExpressionSyntax ce:
                return $"(function() if {Expr(ce.Condition)} then return {Expr(ce.WhenTrue)} else return {Expr(ce.WhenFalse)} end end)()";
            case CastExpressionSyntax cast:
                return Cast(model.GetTypeInfo(cast.Type).Type, cast.Expression);
            case ObjectCreationExpressionSyntax oc:
                return Creation(oc.Type.ToString(), oc, oc.ArgumentList, oc.Initializer);
            case ImplicitObjectCreationExpressionSyntax ioc:
                return Creation(model.GetTypeInfo(ioc).Type?.Name ?? "Object", ioc, ioc.ArgumentList, ioc.Initializer);
            case ArrayCreationExpressionSyntax ac:
                return ac.Initializer != null ? ListLit(ac.Initializer.Expressions.Select(Expr)) : $"ARRAY({Expr(ac.Type.RankSpecifiers[0].Sizes[0])})";
            case ImplicitArrayCreationExpressionSyntax iac:
                return ListLit(iac.Initializer.Expressions.Select(Expr));
            case CollectionExpressionSyntax col:
                return $"LIST({string.Join(", ", col.Elements.OfType<ExpressionElementSyntax>().Select(x => Expr(x.Expression)))})";
            case ElementAccessExpressionSyntax ea:
                return $"IDX({Expr(ea.Expression)}, {Expr(ea.ArgumentList.Arguments[0].Expression)})";
            case ConditionalAccessExpressionSyntax ca:
                return ConditionalAccess(ca);
            case SimpleLambdaExpressionSyntax sl:
                return Lambda(new[] { sl.Parameter.Identifier.Text }, sl.Body);
            case ParenthesizedLambdaExpressionSyntax pl:
                return Lambda(pl.ParameterList.Parameters.Select(p => p.Identifier.Text).ToArray(), pl.Body);
            case AnonymousMethodExpressionSyntax am:
                return Lambda(am.ParameterList?.Parameters.Select(p => p.Identifier.Text).ToArray() ?? Array.Empty<string>(), am.Block);
            case InterpolatedStringExpressionSyntax istr:
                return Interpolated(istr);
            case TypeOfExpressionSyntax to:
                return TypeArg(to.Type);
            case DefaultExpressionSyntax de:
                return DefaultFor(model.GetTypeInfo(de.Type).Type);
            case IsPatternExpressionSyntax ip:
                return Pattern(Expr(ip.Expression), ip.Pattern);
            case SwitchExpressionSyntax se:
                return SwitchExpr(se);
            case AssignmentExpressionSyntax asg:
                // assignment used as an expression: evaluate in a closure and yield the value
                return $"(function() {Assign(asg)}; return {Expr(asg.Left)} end)()";
            case PredefinedTypeSyntax pt:
                return Name(model.GetTypeInfo(pt).Type?.Name ?? pt.ToString());
            case QualifiedNameSyntax qn:
                return Name(qn.Right.Identifier.Text);
            case ThrowExpressionSyntax te:
                return $"error({Expr(te.Expression)})";
            case QueryExpressionSyntax q:
                return Query(q);
            case TupleExpressionSyntax tu:
                return $"LIST({string.Join(", ", tu.Arguments.Select(a => Expr(a.Expression)))})";
        }
        return $"TODO_EXPR({Todo(e)})";
    }

    static string ConstLit(object v) => v switch
    {
        null => "nil",
        string s => Lit(s),
        char c => Lit(c.ToString()),
        bool b => b ? "true" : "false",
        float f => f.ToString("R", System.Globalization.CultureInfo.InvariantCulture),
        double d => d.ToString("R", System.Globalization.CultureInfo.InvariantCulture),
        decimal m => m.ToString(System.Globalization.CultureInfo.InvariantCulture),
        _ => Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture),
    };

    string Identifier(SimpleNameSyntax id)
    {
        var sym = model.GetSymbolInfo(id).Symbol ?? model.GetSymbolInfo(id).CandidateSymbols.FirstOrDefault();
        string n = Name(id.Identifier.Text);
        switch (sym)
        {
            case IFieldSymbol f when f.ContainingType?.TypeKind == TypeKind.Enum:
                return Lit(f.Name);
            case IFieldSymbol or IPropertySymbol or IEventSymbol:
                if (sym.IsStatic) return $"{TypeRef(sym.ContainingType)}.{n}";
                return $"self.{n}";
            case IMethodSymbol m:
                // method group used as a delegate
                if (m.IsStatic) return $"{TypeRef(m.ContainingType)}.{MethodName(m)}";
                return $"function(...) return self:{MethodName(m)}(...) end";
            case INamedTypeSymbol t:
                return TypeRef(t);
        }
        return n;
    }

    string TypeRef(INamedTypeSymbol t)
    {
        if (t == null) return "nil";
        if (t.Name == "Random" && t.ContainingNamespace?.ToString() == "UnityEngine") return "Random";
        return Name(t.Name);
    }

    string MemberAccess(MemberAccessExpressionSyntax ma)
    {
        var sym = model.GetSymbolInfo(ma).Symbol ?? model.GetSymbolInfo(ma).CandidateSymbols.FirstOrDefault();
        string member = Name(ma.Name.Identifier.Text);

        if (sym is IFieldSymbol ef && ef.ContainingType?.TypeKind == TypeKind.Enum) return Lit(ef.Name);
        // SingletonMonoBehaviour<T>.Instance / X.Instance  ->  T / X (runtime singletons)
        if (member == "Instance" && sym is IPropertySymbol { IsStatic: true } ip)
        {
            if (ma.Expression is GenericNameSyntax g && g.Identifier.Text == "SingletonMonoBehaviour")
                return Name(g.TypeArgumentList.Arguments[0].ToString().Split('.').Last());
            return TypeRef(ip.ContainingType);
        }
        if (ma.Expression is BaseExpressionSyntax) return $"self.{member}";
        if (sym != null && sym.IsStatic && sym is not IMethodSymbol)
            return $"{TypeRef(sym.ContainingType)}.{member}";
        if (sym is IPropertySymbol { Name: "Length" } && IsString(ma.Expression))
            return $"STR.Length({Expr(ma.Expression)})";
        return $"{Recv(ma.Expression)}.{member}";
    }

    string Recv(ExpressionSyntax e)
    {
        string r = Expr(e);
        bool simple = e is IdentifierNameSyntax or MemberAccessExpressionSyntax or ThisExpressionSyntax or InvocationExpressionSyntax or ElementAccessExpressionSyntax or GenericNameSyntax;
        return simple && !r.StartsWith("\"") && !r.StartsWith("(function") ? r : "(" + r + ")";
    }

    string Invocation(InvocationExpressionSyntax inv)
    {
        var si = model.GetSymbolInfo(inv);
        var m = (si.Symbol ?? si.CandidateSymbols.FirstOrDefault()) as IMethodSymbol;
        string typeArgs = "";
        SimpleNameSyntax nameNode = inv.Expression switch
        {
            MemberAccessExpressionSyntax ma => ma.Name,
            SimpleNameSyntax sn => sn,
            MemberBindingExpressionSyntax mb => mb.Name,
            _ => null,
        };
        var defM = m?.ReducedFrom ?? m;
        if (m != null && m.IsGenericMethod && defM.ContainingType != null && translated.Contains(defM.ContainingType.Name))
        {
            // generic methods of game code always receive their (possibly inferred) type arguments
            typeArgs = string.Join(", ", m.TypeArguments.Select(t => t is ITypeParameterSymbol tp ? Name(tp.Name) : Lit(t.Name)));
        }
        else if (nameNode is GenericNameSyntax gname)
            typeArgs = string.Join(", ", gname.TypeArgumentList.Arguments.Select(TypeArg));
        string args = Args(inv.ArgumentList, m);
        string all = typeArgs.Length > 0 ? (args.Length > 0 ? typeArgs + ", " + args : typeArgs) : args;

        if (m == null)
        {
            if (inv.Expression is IdentifierNameSyntax { Identifier.Text: "nameof" })
                return Lit(inv.ArgumentList.Arguments[0].ToString().Split('.').Last());
            // dynamic / unresolved: best effort
            return $"{Expr(inv.Expression)}({all})";
        }
        string mname = MethodName(m);
        string ctype = (m.ReducedFrom ?? m).ContainingType?.Name;

        // delegate invocation
        if (m.MethodKind == MethodKind.DelegateInvoke)
        {
            string target = inv.Expression is MemberAccessExpressionSyntax { Name.Identifier.Text: "Invoke" } dm ? Expr(dm.Expression) : Expr(inv.Expression);
            return $"{target}({all})";
        }
        // LINQ Count() clashes with the Count property in Lua
        if (mname == "Count" && m.ReducedFrom != null && inv.Expression is MemberAccessExpressionSyntax cma)
            return $"LCOUNT({Expr(cma.Expression)}{(all.Length > 0 ? ", " + all : "")})";
        // UniTask continuations: the awaited call itself is the task in Lua
        if (inv.Expression is MemberAccessExpressionSyntax tma && IsTaskType(model.GetTypeInfo(tma.Expression).Type))
        {
            if (mname == "Forget") return $"spawn(function() {Expr(tma.Expression)} end)";
            if (mname is "AttachExternalCancellation" or "SuppressCancellationThrow" or "ConfigureAwait" or "Preserve")
                return Expr(tma.Expression);
        }
        // BCL helpers
        if (mname == "ToString" && m.Parameters.Length == 0 && inv.Expression is MemberAccessExpressionSyntax tsm)
            return $"TOSTR({Expr(tsm.Expression)})";
        if (ctype == "String" || (m.ReducedFrom == null && !m.IsStatic && m.ContainingType?.SpecialType == SpecialType.System_String))
        {
            if (m.IsStatic) return $"STR.{mname}({all})";
            var recvExpr = ((MemberAccessExpressionSyntax)inv.Expression).Expression;
            return $"STR.{mname}({Expr(recvExpr)}{(all.Length > 0 ? ", " + all : "")})";
        }

        switch (inv.Expression)
        {
            case MemberAccessExpressionSyntax ma:
                if (ma.Expression is BaseExpressionSyntax)
                    return $"C.super.{mname}(self{(all.Length > 0 ? ", " + all : "")})";
                if (m.IsStatic && m.ReducedFrom == null)
                    return $"{TypeRef(m.ContainingType)}.{mname}({all})";
                // the game's own extension methods: static call (the receiver may be a string or nil)
                if (m.ReducedFrom != null && translated.Contains(m.ReducedFrom.ContainingType.Name))
                    return $"{TypeRef(m.ReducedFrom.ContainingType)}.{mname}({(typeArgs.Length > 0 ? typeArgs + ", " : "")}{Expr(ma.Expression)}{(args.Length > 0 ? ", " + args : "")})";
                return $"{Recv(ma.Expression)}:{mname}({all})";
            case MemberBindingExpressionSyntax:
                return $"{condReceivers.Peek()}:{mname}({all})";
            case SimpleNameSyntax:
                if (m.IsStatic) return $"{TypeRef(m.ContainingType)}.{mname}({all})";
                if (m.MethodKind == MethodKind.LocalFunction) return $"{mname}({all})";
                return $"self:{mname}({all})";
        }
        return $"{Expr(inv.Expression)}({all})";
    }

    // a type used as a value: its name, or the variable holding it inside a generic method
    string TypeArg(TypeSyntax t)
    {
        var sym = model.GetTypeInfo(t).Type;
        if (sym is ITypeParameterSymbol tp) return Name(tp.Name);
        return Lit(sym?.Name is { Length: > 0 } n && sym.TypeKind != TypeKind.Error ? n : t.ToString().Split('.').Last());
    }

    // Arguments in declaration order: named args are placed by parameter, omitted optionals get their default.
    string Args(ArgumentListSyntax al, IMethodSymbol m)
    {
        if (al == null) return "";
        if (m == null) return string.Join(", ", al.Arguments.Select(a => ArgExpr(a)).Where(x => x != null));
        var ps = (m.ReducedFrom != null ? m.ReducedFrom.Parameters.Skip(1) : m.Parameters).Where(p => p.RefKind != RefKind.Out).ToList();
        var slots = new string[ps.Count];
        var extra = new List<string>();
        int pos = 0;
        foreach (var a in al.Arguments.Where(x => !x.RefKindKeyword.IsKind(SyntaxKind.OutKeyword)))
        {
            int idx = a.NameColon != null ? ps.FindIndex(p => p.Name == a.NameColon.Name.Identifier.Text) : pos;
            pos = idx + 1;
            if (idx >= 0 && idx < ps.Count && !ps[idx].IsParams) slots[idx] = ArgExpr(a);
            else extra.Add(ArgExpr(a));
        }
        int lastGiven = Array.FindLastIndex(slots, s => s != null);
        var outArgs = new List<string>();
        // omitted optional arguments are always passed explicitly (Lua has no default parameters)
        for (int i = 0; i < ps.Count; i++)
        {
            if (slots[i] != null) outArgs.Add(slots[i]);
            else if (ps[i].HasExplicitDefaultValue)
                outArgs.Add(ps[i].Type.TypeKind == TypeKind.Enum ? EnumName(ps[i].Type, ps[i].ExplicitDefaultValue) : ConstLit(ps[i].ExplicitDefaultValue));
            else if (i > lastGiven) break;
            else outArgs.Add("nil");
        }
        while (outArgs.Count > 0 && outArgs[^1] == "nil" && outArgs.Count - 1 > lastGiven) outArgs.RemoveAt(outArgs.Count - 1);
        outArgs.AddRange(extra);
        return string.Join(", ", outArgs);
    }

    static string EnumName(ITypeSymbol enumType, object value)
    {
        if (value == null) return "nil";
        var f = enumType.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(x => x.HasConstantValue && Convert.ToInt64(x.ConstantValue) == Convert.ToInt64(value));
        return f != null ? Lit(f.Name) : ConstLit(value);
    }

    string ArgExpr(ArgumentSyntax a)
    {
        if (a.RefKindKeyword.IsKind(SyntaxKind.OutKeyword)) return null;   // returned as an extra value instead
        if (!a.RefKindKeyword.IsKind(SyntaxKind.None))
            return $"TODO_EXPR({Todo(a)})";
        return Expr(a.Expression);
    }

    // out arguments: F(a, out x) -> (function() local __r; __r, x = F(a); return __r end)()
    string OutTarget(ArgumentSyntax a) => a.Expression switch
    {
        DeclarationExpressionSyntax { Designation: SingleVariableDesignationSyntax v } => Name(v.Identifier.Text),
        DeclarationExpressionSyntax => "_",
        IdentifierNameSyntax { Identifier.Text: "_" } => "_",
        _ => Expr(a.Expression),
    };

    // `out var x` inside a statement needs `local x` declared before it
    void DeclareOutVars(SyntaxNode stmt)
    {
        var names = stmt.DescendantNodes(n => n == stmt || !(n is LambdaExpressionSyntax or BlockSyntax or StatementSyntax))
            .OfType<ArgumentSyntax>().Where(a => a.RefKindKeyword.IsKind(SyntaxKind.OutKeyword))
            .Select(a => a.Expression).OfType<DeclarationExpressionSyntax>()
            .Select(d => d.Designation).OfType<SingleVariableDesignationSyntax>()
            .Select(v => Name(v.Identifier.Text)).Distinct().ToList();
        if (names.Count > 0) Line($"local {string.Join(", ", names)}");
    }

    string Binary(BinaryExpressionSyntax be)
    {
        string op = be.OperatorToken.Text;
        if (be.IsKind(SyntaxKind.AsExpression)) return Expr(be.Left);
        if (be.IsKind(SyntaxKind.IsExpression)) return $"IS({Expr(be.Left)}, {Lit(be.Right.ToString().Split('.').Last())})";
        if (be.IsKind(SyntaxKind.CoalesceExpression)) return $"nz({Expr(be.Left)}, {Expr(be.Right)})";
        string l = Expr(be.Left), r = Expr(be.Right);
        switch (op)
        {
            case "&&": return $"{l} and {r}";
            case "||": return $"{l} or {r}";
            case "!=": return $"{l} ~= {r}";
            case "==": return $"{l} == {r}";
            case "+":
                if (model.GetTypeInfo(be).Type?.SpecialType == SpecialType.System_String) return $"CONCAT({l}, {r})";
                break;
            case "/":
                if (IsIntegral(be.Left) && IsIntegral(be.Right)) return $"IDIV({l}, {r})";
                break;
            case "%": return $"MOD({l}, {r})";
            case "&": return model.GetTypeInfo(be).Type?.SpecialType == SpecialType.System_Boolean ? $"({l} and {r})" : $"BITAND({l}, {r})";
            case "|": return model.GetTypeInfo(be).Type?.SpecialType == SpecialType.System_Boolean ? $"({l} or {r})" : $"BITOR({l}, {r})";
            case "^": return $"BITXOR({l}, {r})";
            case "<<": return $"({l} << {r})";
            case ">>": return $"({l} >> {r})";
        }
        if (op is "<" or ">" or "<=" or ">=" or "-" or "+")
        {
            if (IsEnum(be.Left)) l = $"ENUMV({Lit(model.GetTypeInfo(be.Left).Type.Name)}, {l})";
            if (IsEnum(be.Right)) r = $"ENUMV({Lit(model.GetTypeInfo(be.Right).Type.Name)}, {r})";
        }
        return $"{l} {op} {r}";
    }

    string Cast(ITypeSymbol to, ExpressionSyntax inner)
    {
        string v = Expr(inner);
        var from = model.GetTypeInfo(inner).Type;
        if (to == null) return v;
        if (to.TypeKind == TypeKind.Enum && from?.TypeKind != TypeKind.Enum) return $"ENUMN({Lit(to.Name)}, {v})";
        if (from?.TypeKind == TypeKind.Enum && to.TypeKind != TypeKind.Enum) return $"ENUMV({Lit(from.Name)}, {v})";
        if (to.SpecialType is SpecialType.System_Int32 or SpecialType.System_Int64 or SpecialType.System_Int16 or SpecialType.System_Byte &&
            from?.SpecialType is SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_Decimal)
            return $"TRUNC({v})";
        return v;
    }

    string Creation(string typeName, ExpressionSyntax node, ArgumentListSyntax args, InitializerExpressionSyntax init)
    {
        var type = model.GetTypeInfo(node).Type as INamedTypeSymbol;
        string tname = type?.Name ?? typeName.Split('<')[0].Split('.').Last();
        var ctor = model.GetSymbolInfo(node).Symbol as IMethodSymbol;
        string a = Args(args, ctor);
        string ctorIdx = translated.Contains(tname) ? CtorIndex(ctor).ToString() : "nil";
        string created;
        if (type != null && type.TypeKind == TypeKind.Delegate)
            return a;
        if (init != null && init.IsKind(SyntaxKind.CollectionInitializerExpression))
        {
            var items = init.Expressions.Select(x => x is InitializerExpressionSyntax kv
                ? $"LIST({string.Join(", ", kv.Expressions.Select(Expr))})" : Expr(x));
            if (tname is "Dictionary" or "ReactiveDictionary") return ListLit(items, "DICT");
            if (tname is "List" or "IList" or "IEnumerable" or "IReadOnlyList") return ListLit(items, "LIST");
            return $"ADDALL(NEW({Lit(tname)}, nil), {{{string.Join(", ", items)}}})";
        }
        string tref = model.GetTypeInfo(node).Type is ITypeParameterSymbol tpar ? Name(tpar.Name) : Lit(tname);
        created = $"NEW({tref}, {ctorIdx}{(a.Length > 0 ? ", " + a : "")})";
        if (init != null && init.IsKind(SyntaxKind.ObjectInitializerExpression))
        {
            var fields = init.Expressions.OfType<AssignmentExpressionSyntax>()
                .Select(x => $"{Name(((IdentifierNameSyntax)x.Left).Identifier.Text)} = {Expr(x.Right)}");
            created = $"INIT({created}, {{ {string.Join(", ", fields)} }})";
        }
        return created;
    }

    // LIST(a, b, ...) hits Lua's register limit for big literals; use a table constructor instead
    static string ListLit(IEnumerable<string> items, string fn = "LIST")
    {
        var l = items.ToList();
        if (l.Count > 60) return $"{fn}T({{{string.Join(", ", l)}}})";
        return $"{fn}({string.Join(", ", l)})";
    }

    string ConditionalAccess(ConditionalAccessExpressionSyntax ca)
    {
        // singletons are always present on the 3DS runtime: X.Instance?.M() -> X:M()
        string recv = Expr(ca.Expression);
        if (ca.Expression is MemberAccessExpressionSyntax { Name.Identifier.Text: "Instance" })
        {
            condReceivers.Push(recv);
            string direct = Expr(ca.WhenNotNull);
            condReceivers.Pop();
            return direct;
        }
        string t = "__t" + (++tmp);
        condReceivers.Push(t);
        string body = Expr(ca.WhenNotNull);
        condReceivers.Pop();
        return $"(function({t}) if {t} ~= nil then return {body} end end)({recv})";
    }

    string Lambda(string[] ps, CSharpSyntaxNode body)
    {
        var saved = sb.Length;
        string head = $"function({string.Join(", ", ps.Select(Name))})";
        if (body is ExpressionSyntax ex)
        {
            if (ex is AssignmentExpressionSyntax asg) return $"{head} {Assign(asg)} end";
            if (ex is PostfixUnaryExpressionSyntax or PrefixUnaryExpressionSyntax && (ex.IsKind(SyntaxKind.PostIncrementExpression) || ex.IsKind(SyntaxKind.PostDecrementExpression)))
                return $"{head} {IncDec(((PostfixUnaryExpressionSyntax)ex).Operand, ex.IsKind(SyntaxKind.PostIncrementExpression) ? "+" : "-")} end";
            return $"{head} return {Expr(ex)} end";
        }
        // block body: render into a temporary buffer at the current indentation
        var outer = sb.ToString(saved, sb.Length - saved);
        sb.Length = saved;
        int savedIndent = indent;
        indent++;
        Block(((BlockSyntax)body).Statements);
        indent = savedIndent;
        string inner = sb.ToString(saved, sb.Length - saved);
        sb.Length = saved;
        sb.Append(outer);
        return $"{head}\n{inner}{new string(' ', indent * 2)}end";
    }

    string Interpolated(InterpolatedStringExpressionSyntax istr)
    {
        var parts = new List<string>();
        foreach (var c in istr.Contents)
        {
            if (c is InterpolatedStringTextSyntax t) parts.Add(Lit(t.TextToken.ValueText));
            else if (c is InterpolationSyntax i)
                parts.Add(i.FormatClause != null ? $"FMT({Expr(i.Expression)}, {Lit(i.FormatClause.FormatStringToken.ValueText)})" : $"TOSTR({Expr(i.Expression)})");
        }
        return parts.Count == 0 ? "\"\"" : "(" + string.Join(" .. ", parts) + ")";
    }

    // from x in SRC [where C]* select E  ->  SRC:Where(function(x) ... end):Select(function(x) ... end)
    string Query(QueryExpressionSyntax q)
    {
        string v = Name(q.FromClause.Identifier.Text);
        string chain = Recv(q.FromClause.Expression);
        foreach (var clause in q.Body.Clauses)
        {
            if (clause is WhereClauseSyntax w) chain += $":Where(function({v}) return {Expr(w.Condition)} end)";
            else return $"TODO_EXPR({Todo(q)})";
        }
        if (q.Body.SelectOrGroup is SelectClauseSyntax sel)
        {
            if (!(sel.Expression is IdentifierNameSyntax id && id.Identifier.Text == q.FromClause.Identifier.Text))
                chain += $":Select(function({v}) return {Expr(sel.Expression)} end)";
            return chain;
        }
        return $"TODO_EXPR({Todo(q)})";
    }

    string SwitchExpr(SwitchExpressionSyntax se)
    {
        string v = "__v" + (++tmp);
        var arms = new StringBuilder($"(function({v}) ");
        foreach (var arm in se.Arms)
        {
            string cond = Pattern(v, arm.Pattern) + (arm.WhenClause != null ? $" and ({Expr(arm.WhenClause.Condition)})" : "");
            arms.Append($"if {cond} then return {Expr(arm.Expression)} end ");
        }
        arms.Append($"end)({Expr(se.GoverningExpression)})");
        return arms.ToString();
    }
