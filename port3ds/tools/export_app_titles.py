"""Window titles of every app (AppTypeToDataAsset "Apps": AppList, then AppDiffForSteam, the order
LoadAppData.ReadAppContent finds them in) -> lua/ui/app_titles.lua as AppType -> SystemTextType.

usage: python -I export_app_titles.py <assets dir> <port3ds/lua dir>
"""
import json
import os
import re
import sys

ASSETS, LUA = sys.argv[1], sys.argv[2]
apps = json.load(open(os.path.join(ASSETS, "MonoBehaviour", "Apps.json"), encoding="utf-8"))
enums = open(os.path.join(LUA, "enums.lua"), encoding="utf-8").read()


def enum(name):
    m = re.search(r'E\["%s"\] = \{(.*?)\}\n' % name, enums, re.S)
    return {int(v): k for k, v in re.findall(r'\["(\w+)"\] = (-?\d+)', m.group(1))}


app_type, text_type = enum("AppType"), enum("SystemTextType")
titles = {}
for a in apps["AppList"] + apps["AppDiffForSteam"]:
    t, n = app_type.get(a["appType"]), text_type.get(a["AppName"])
    if t and n and t not in titles:
        titles[t] = n
with open(os.path.join(LUA, "ui", "app_titles.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- AppType -> SystemTextType of the window title (generated by tools/export_app_titles.py)\nreturn {\n")
    for t in sorted(titles):
        f.write('  %s = "%s",\n' % (t, titles[t]))
    f.write("}\n")
print(len(titles), "app titles")
