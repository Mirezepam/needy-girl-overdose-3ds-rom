"""Exports the content of the Ending_Ideon site windows (App_ideon*, App_insta, App_news, App_taiki)
from the dumped prefabs to data/ideon.lua: texts in layout order with colour and size, and the
images worth showing. Texts whose Japanese placeholder matches a SystemText entry are stored by id
so the 3DS shows them in the chosen language.

usage: python -I export_ideon.py <port3ds dir>
"""
import json
import re
import sys

ROOT = sys.argv[1]
APPS = {"Ideon_2ch": "App_ideon2ch", "Ideon_nico": "App_ideonNico", "Ideon_hutaba": "App_ideonhutaba",
        "Ideon_wiki": "App_ideonwiki", "Ideon_Insta": "App_insta", "Ideon_news": "App_news",
        "Ideon_taiki": "App_taiki"}
SKIP_SPRITES = {"UIMask", "Background", "UISprite", "haisin", "InputFieldBackground", "Square"}


def norm(s):
    return re.sub(r"\s+", "", s)


ja = open(ROOT + "/build_data/needy3ds/text/ja.lua", encoding="utf-8").read()
byval = {}
for k, v in re.findall(r'\["([^"]+)"\]="((?:[^"\\]|\\.)*)"', ja):
    byval.setdefault(norm(v.replace("\\n", "\n")), k)


def col(c):
    return "0x%02x%02x%02x%02x" % tuple(int(round(x * 255)) for x in c) if c else "0x4d22cfff"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n") + '"'


out = ["-- generated by tools/export_ideon.py: Ending_Ideon site windows, items in layout order",
       "-- {t=text or id=SystemText id, c=colour, s=size(px at 1080p)} / {img=sprite}", "return {"]
for app, prefab in APPS.items():
    d = json.load(open(ROOT + "/build_data/prefabs/%s.json" % prefab, encoding="utf-8"))
    items = []

    def walk(n):
        if not n.get("active", True):
            return
        for u in n.get("ui", []):
            t = u.get("m_text")
            if t and t.strip():
                k = byval.get(norm(t))
                if not k:
                    # some prefab texts are the master text repeated or with extra lines
                    # (Ideon_wiki_res2 twice): match the longest master text they contain
                    nt = norm(t)
                    cands = [(len(v), key) for v, key in byval.items() if len(v) >= 8 and v in nt]
                    k = max(cands)[1] if cands else None
                c = col(u.get("fontColor"))
                s = u.get("m_fontSize") or 20
                if k:
                    items.append("{id=%s,t=%s,c=%s,s=%d}" % (lua_str(k), lua_str(t), c, s))
                else:
                    items.append("{t=%s,c=%s,s=%d}" % (lua_str(t), c, s))
            sp = u.get("sprite")
            if sp and sp not in SKIP_SPRITES and u.get("class") == "Image":
                items.append("{img=%s}" % lua_str(sp))
        for ch in n.get("children", []):
            walk(ch)

    walk(d)
    out.append("[%s]={%s}," % (lua_str(app), ",".join(items)))
out.append("}")
open(ROOT + "/build_data/needy3ds/data/ideon.lua", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("ideon windows exported:", len(APPS))
